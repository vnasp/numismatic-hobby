/**
 * Íconos de la navegación, en SVG inline.
 *
 * Van como componentes y no como archivos ni como fuente de íconos para que
 * hereden `currentColor` (la pestaña activa se pinta con el acento sin lógica
 * extra) y para no sumar una petición de red a una PWA que ya precachea todo.
 */

interface IconProps {
  size?: number
}

function Icon({ size = 24, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.7"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  )
}

